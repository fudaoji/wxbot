            ->addFormItem('deadline', 'datetime', '到期时间', '到期时间', [], 'required')
            ->setFormData(['type' => ApplyService::WECHAT]);

        return $builder->show();
    }

    public function edit(){
        $id = input('id');
        $data = $this->model->getOne($id);
        if(! $data){
            $this->error('id参数错误');
        }
        //使用FormBuilder快速建立表单页面。
        $builder = new FormBuilder();
        $builder->setMetaTitle('编辑')  //设置页面标题
            ->setPostUrl(url('savepost')) //设置表单提交地址
            ->addFormItem('id', 'hidden', 'id', 'id')
            ->addFormItem('type', 'radio', '类型', '类型', ApplyService::types(), 'required')
            ->addFormItem('admin_id', 'chosen', '所属客户', '所属客户', AdminM::getTenantIdToName(), 'required')
            ->addFormItem('deadline', 'datetime', '到期时间', '到期时间', [], 'required')
            ->setFormData($data);
        return $builder->show();
    }

    public function savePost($jump_to = '/undefined', $data = [])
    {
        $data = input('post.');
        $data['deadline'] = strtotime($data['deadline']);
        parent::savePost($jump_to, $data); // TODO: Change the autogenerated stub
    }

    /**
     * 站长端申请列表
     * @return mixed
     * @throws \think\db\exception\DataNotFoundException
     * @throws \think\db\exception\DbException
     * @throws \think\db\exception\ModelNotFoundException
     * Author: fudaoji<fdj@kuryun.cn>
     */
    public function applyList(){
        if(request()->isPost()){
            $post_data = input('post.');
            $where = [];
            !empty($post_data['search_key']) && $where['apply.wx_num|admin.username|admin.mobile'] = ['like', '%'.$post_data['search_key'].'%'];
            if(isset($post_data['deadline_status']) && $post_data['deadline_status'] != 0){
                $where['apply.deadline'] = [$post_data['deadline_status'] == 2 ? '<' : '>', time()];
            }
            $params = [
                'alias' => 'apply',
                'join' => [
                    ['admin', 'admin.id=apply.admin_id']
                ],
                'where' => $where,
                'refresh' => true
            ];
            $total = $this->model->totalJoin($params);
            if ($total) {
                $list = $this->model->getListJoin(array_merge($params, [
                    'limit' => [$post_data['page'], $post_data['limit']],
                    'order' => ['apply.id' => 'desc'],
                    'field' => ['admin.username', 'admin.mobile', 'apply.*']
                ]));
                foreach ($list as $k => $v){
                    $v['admin_info'] = '账号：'.$v['username'] . '<br>手机号：'.$v['mobile'];
                    $v['deadline_status'] = $v['deadline'] > time() ? '未过期' : '已过期';
                    $v['deadline'] = date('Y-m-d H:i', $v['deadline']);
                    $v['type_title'] = ApplyService::types($v['type']);
                    $list[$k] = $v;
                }
            } else {
                $list = [];
            }

            $this->success('success', '', ['total' => $total, 'list' => $list]);
        }

        $deadline_status = [0 => '所有', 1=>'未过期', 2 => '已过期'];
        $builder = new ListBuilder();
        $builder->setSearch([
            ['type' => 'text', 'name' => 'search_key', 'title' => '搜索词','placeholder' => 'Wxid/客户手机号/客户账号'],
            ['type' => 'select', 'name' => 'deadline_status', 'title' => '过期状态','options' => $deadline_status]
        ])
            ->addTopButton('addnew', ['text' => '新增席位'])
            ->addTableColumn(['title' => '序号', 'type' => 'index'])
            ->addTableColumn(['title' => '类型', 'field' => 'type_title'])
            ->addTableColumn(['title' => '客户信息', 'field' => 'admin_info'])
            ->addTableColumn(['title' => '绑定Wxid', 'field' => 'wx_num'])
            //->addTableColumn(['title' => '有效时间(个月)', 'field' => 'month'])
            ->addTableColumn(['title' => '到期时间', 'field' => 'deadline'])
            ->addTableColumn(['title' => '状态', 'field' => 'deadline_status'])
            //->addTableColumn(['title' => '申请时间', 'field' => 'create_time', 'type' => 'datetime'])
            ->addTableColumn(['title' => '操作', 'width' => 100, 'type' => 'toolbar'])
            ->addRightButton('edit');
        return $builder->show();
    }

    /**
     * 审核操作
     * @return mixed
     * @throws \think\Exception
     * @throws \think\db\exception\DataNotFoundException
     * @throws \think\db\exception\DbException
     * @throws \think\db\exception\ModelNotFoundException
     * Author: fudaoji<fdj@kuryun.cn>
     */
    public function verify(){
        $id = input('id');
        $data = $this->model->getOne($id);
        if(! $data){
            $this->error('id参数错误');
        }

        if(request()->isPost()){
            $post_data = input('post.');
            if($post_data['status'] == Common::VERIFY_SUCCESS){
                $post_data['deadline'] = strtotime("+" . $post_data['month'] . ' months', max($data['deadline'], time()));
            }
            return parent::savePost('', $post_data);
        }

        if(! AdminM::isFounder($this->adminInfo)){
            $this->error('非法操作');
        }

        //使用FormBuilder快速建立表单页面。
        $builder = new FormBuilder();
        $builder->setMetaTitle('新增')  //设置页面标题
            ->setPostUrl(url('verify')) //设置表单提交地址
        ->addFormItem('id', 'hidden', 'id', 'id')
            ->addFormItem('wx_num', 'text', '微信号', '请输入微信号', [], 'required minlength=4 maxlength=50')
            ->addFormItem('month', 'number', '要开几个月', '从当前时间开始算', [], 'required min=1')
            ->addFormItem('status', 'radio', '状态', '请选择审核状态', Common::verifies(), 'required')
            ->setFormData($data);
        return $builder->show();
    }
}