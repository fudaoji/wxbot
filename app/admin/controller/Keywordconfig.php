<?php

namespace app\admin\controller;

use app\common\model\KeywordConfig as M;
use app\common\service\KeywordConfig as ConfigService;
use app\constants\Bot;

class Keywordconfig extends Botbase
{
    /**
     * @var M
     */
    protected $model;

    public function initialize()
    {
        parent::initialize(); // TODO: Change the autogenerated stub
        $this->model = new M();
    }

    /**
     * 设置
     * @return mixed
     * @throws \think\Exception
     * @author: fudaoji<fdj@kuryun.cn>
     */
    public function index()
    {
        $settings = ConfigService::getConf(['bot_id' => $this->bot['id']]);
        if (!empty($settings['wxids'])) {
            $settings['wxids'] = explode(',', $settings['wxids']);
        } else {
            $settings['wxids'] = [];
        }

        $builder = new FormBuilder();
        $builder->setPostUrl(url('savepost'))
            ->addFormItem('id', 'hidden', 'id', 'id')
            ->addFormItem('wxids', 'chosen_multi', '白名单', '填写白名单后表示只有白名单的好友才能使用智能对话，为空表示所有人生效', $this->getMembers());

        return $builder->setFormData($settings)->show();
    }

    public function savePost($jump_to = '/undefined', $data = [])
    {

        $post_data = input('post.');
        unset($post_data['__token__']);
        foreach ($post_data as $k => $v) {
            if ($config = $this->model->getOneByMap(['bot_id' => $this->bot['id'], 'key' => $k],  true, true)) {
                $this->model->updateOne(['id' => $config['id'], 'value' => $v]);
            } else {
                $this->model->addOne([
                    'admin_id' => $this->adminInfo['id'],
                    'bot_id' => $this->bot['id'],
                    'key' => $k,
                    'value' => $v
                ]);
            }
        }
        ConfigService::getConf(['bot_id' => $this->bot['id']], '', true);
        $this->success('数据保存成功', $jump_to);
    }
}
