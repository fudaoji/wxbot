namespace app\admin\controller;
use app\common\model\Server as ServerM;
use app\constants\Common;
use app\common\service\Server as ServerService;

class Server extends Bbase
{

    /**
     * @var ServerM
     */
    protected $model;
    /**
     * @var array
     */
    private $tabList;

    public function initialize()
    {
        parent::initialize(); // TODO: Change the autogenerated stub
        $this->model = new ServerM();
        $this->tabList = [
            'local' => ['title' => '添加本地主机', 'href' => url('addLocal')],
            'cloud' => ['title' => '添加云服务器', 'href' => url('add')]
        ];
    }

    public function index(){
        if(request()->isPost()){
            $post_data = input('post.');
            $where = ['admin_id' => $this->aid];
            !empty($post_data['search_key']) && $where['url|name'] = ['like', '%'.$post_data['search_key'].'%'];

            $total = $this->model->total($where, true);
            if (! $total) {
                ServerService::initServer();
                $total = $this->model->total($where, true);
            }
            $list = $this->model->getList([$post_data['page'], $post_data['limit']], $where, ['id' => 'desc'], true, 1);
            $this->success('success', '', ['total' => $total, 'list' => $list]);
        }
        $tip = "<ul><li>只有当机器人驱动使用e小天时才需要管理此处的设备！</li></ul>";
        $builder = new ListBuilder();
        $builder->setSearch([
            ['type' => 'text', 'name' => 'search_key', 'title' => '搜索词','placeholder' => '隧道名称|接口地址']
        ])
            ->setTip($tip)
            ->addTopButton('addnew', ['title' => '添加服务器', 'href' => url('addLocal')])
            ->addTableColumn(['title' => '序号', 'type' => 'index'])
            ->addTableColumn(['title' => '隧道名称', 'field' => 'name', 'minWidth' => 80])
            ->addTableColumn(['title' => '接口地址', 'field' => 'url', 'minWidth' => 200])
            ->addTableColumn(['title' => 'Appkey', 'field' => 'app_key', 'minWidth' => 100])
            ->addTableColumn(['title' => '创建时间', 'field' => 'create_time', 'type' => 'datetime', 'minWidth' => 180])
            ->addTableColumn(['title' => '状态', 'field' => 'status', 'type' => 'switch', 'options' => Common::status()])
            ->addTableColumn(['title' => '操作', 'width' => 220, 'type' => 'toolbar'])
            ->addRightButton('edit')
            ->addRightButton('delete');
        return $builder->show();
    }

