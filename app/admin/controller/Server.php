    /**
     * 编辑云服务器
     */
    public function edit(){
        $id = input('id');
        $data = $this->model->getOne($id);
        if(! $data){
            $this->error('id参数错误');
        }
        //使用FormBuilder快速建立表单页面。
        $builder = new FormBuilder();
        $builder->setMetaTitle('编辑')  //设置页面标题
            ->setPostUrl(url('savepost')) //设置表单提交地址
            ->addFormItem('id', 'hidden', 'id', 'id')
            ->addFormItem('url', 'text', '接口地址', 'ip:port', [], 'required  maxlength="50"')
            ->addFormItem('app_key', 'text', 'Appkey', 'e小天的key', [], 'required')
            //->addFormItem('num', 'number', '承载数量', '承载数量', [], 'required min=1')
            ->setFormData($data);

        return $builder->show();
    }

    /**
     * 保存数据
     * @param string $jump_to
     * @param array $data
     * @return mixed
     * @throws \think\Exception
     */
    public function savePost($jump_to = '/undefined', $data=[]){
        empty($jump_to) && $jump_to = '/undefined';
        $post_data = $data ? $data : input('post.');
        if(empty($post_data['name'])){
            $post_data['name'] = explode(':', $post_data['url'])[0];
        }
        try {
            if(empty($post_data[$this->pk])){
                $this->needAid && $post_data['admin_id'] = $this->adminInfo['id'];
                $res = $this->model->addOne($post_data);
            }else {
                $res = $this->model->updateOne($post_data);
            }
            $msg = '数据保存成功!';
        }catch (\Exception $e){
            $res = false;
            $msg = $e->getMessage();
        }


        if($res){
            $this->success($msg, $jump_to);
        }else{
            $this->error($msg);
        }
    }
}